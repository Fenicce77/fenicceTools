mongoadminusers_bootstrap(){
  declare -a arr=("${@}")
  JSADMINUSERSPATH=${arr[0]}
  ADMINUSER="${arr[1]}"
  CLUSTERADMINUSER="${arr[2]}"
  BKPUSER="${arr[3]}"
  ADMINUSERPWD="${arr[4]}"
  CLUSTERADMINPWD="${arr[5]}"
  BKPPWD="${arr[6]}"
  cat <<EOF > "${JSADMINUSERSPATH}"
/* =============================================================================================
 *   WARNING: This JS script file has been automatically generated by an automation script. 
 *          Please, note that any manual changes may be lost.
 *  
 *  > Auto-generated for bootstrapping MongoDB main basic admin users -> USERS CREATION
 * =============================================================================================
*/

// Create the main administrative user
db.createUser({
  user: "${ADMINUSER}",
  pwd: "${ADMINUSERPWD}",
  roles: [ { role: "root", db: "admin" } ]
});
db.auth("${ADMINUSER}","${ADMINUSERPWD}");

// Create the cluster administrator user (for managing the replica set)
db.createUser({
  user: "${CLUSTERADMINUSER}",
  pwd: "${CLUSTERADMINPWD}",
  roles: [ { role: "clusterAdmin", db: "admin" } ]
});

// Create the user for Percona Backup for MongoDB
db.createUser({
  user: "${BKPUSER}",
  pwd: "${BKPPWD}",
  roles: [
      { role : "backup", db: "admin" },
      { role : "clusterAdmin", db: "admin" },
      { role : "clusterMonitor", db: "admin"},
      { role : "readWriteAnyDatabase", db: "admin" },
      { role : "userAdminAnyDatabase", db: "admin" },
      { role : "restore", db: "admin" }
  ]
});

EOF
}

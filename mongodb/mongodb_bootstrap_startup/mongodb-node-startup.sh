# mongod logrotate configuration
# -- Paramaters info :
# -- * $1 - arr[0] : logrotate configuration file path for mongod
# -- * $2 - arr[1] : mongod log file to rotate
# -- * $3 - arr[2] : mongod pid file
function mongod_logrotate_setup() {
  declare -a arr=("${@}")
  logrotateconfpathfile=${arr[0]}
  mongologpathfile=${arr[1]}
  mongopidpathfile=${arr[2]}
  cat <<EOF > ${logrotateconfpathfile}
# =============================================================================================
#  WARNING: This configuration file has been automatically generated by an automation script. 
#           Please, note that any manual changes may be lost.
# =============================================================================================
#
# ${logrotateconfpathfile}
${mongologpathfile} {
  daily
  size 300M
  rotate 10
  missingok
  compress
  delaycompress
  notifempty
  create 640 mongod mongod
  sharedscripts
  postrotate
    /bin/kill -SIGUSR1 \`cat ${mongopidpathfile} 2>/dev/null\` >/dev/null 2>&1
  endscript
}
EOF
}



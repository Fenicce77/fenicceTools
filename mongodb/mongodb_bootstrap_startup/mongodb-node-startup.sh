# -- Log message function
function log_message(){

  LABEL=$2
  MESSAGE_HEAD_LINE="[`date +"%Y-%m-%d %H:%M:%S"`]${LABEL}"

  case "$3" in
    'OK' ) MESSAGE_TYPE="${grn}${MESSAGE_HEAD_LINE}[OK]"
                     MESSAGE_TYPE_LOG="${MESSAGE_HEAD_LINE}[OK]"
                  ;;
    'INFO' ) MESSAGE_TYPE="${blu}${MESSAGE_HEAD_LINE}[INFO]"
                     MESSAGE_TYPE_LOG="${MESSAGE_HEAD_LINE}[INFO]"
                  ;;
    'ERROR' ) MESSAGE_TYPE="${red}${MESSAGE_HEAD_LINE}[ERROR]"
                            MESSAGE_TYPE_LOG="${MESSAGE_HEAD_LINE}[ERROR]"
                  ;;
    'WARNING' ) MESSAGE_TYPE="${yel}${MESSAGE_HEAD_LINE}[WARN]"
                                  MESSAGE_TYPE_LOG="${MESSAGE_HEAD_LINE}[WARN]"
                  ;;  
  esac

  case "$1" in
    'STANDARD' ) MESSAGE_HEAD="${MESSAGE_TYPE}"
                  ;;
    'LOG' ) MESSAGE_HEAD="${MESSAGE_TYPE_LOG}"
                  ;;
  esac
  MSG=$4

  #MESSAGE_HEAD="${MESSAGE_TYPE}"
  echo "${MESSAGE_HEAD} ${MSG} ${off}"
}

# --- Function for generating Transparent Huge Pages service disabling
function thp_service_disable(){
  cat <<EOF > $1
# =============================================================================================
#  WARNING: This service file has been automatically generated by an automation script. 
#           Please, note that any manual changes may be lost.
# =============================================================================================
# 
# $1
#

[Unit]
Description=Disable Transparent Huge Pages (THP)
DefaultDependencies=no
After=sysinit.target local-fs.target
Before=mongod.service

[Service]
Type=oneshot
ExecStart=/bin/sh -c 'echo never | tee /sys/kernel/mm/transparent_hugepage/enabled > /dev/null'
ExecStart=/bin/sh -c 'echo never | tee /sys/kernel/mm/transparent_hugepage/defrag > /dev/null'

[Install]
WantedBy=multi-user.target
EOF
}

# --- Function for generating Transparent Huge Pages service disabling
function thp_service_enable(){
  cat <<EOF > $1
# =============================================================================================
#  WARNING: This service file has been automatically generated by an automation script. 
#           Please, note that any manual changes may be lost.
# =============================================================================================
# 
# $1
#

[Unit]
Description=Enable Transparent Hugepages (THP)
DefaultDependencies=no
After=sysinit.target local-fs.target
Before=mongod.service

[Service]
Type=oneshot
ExecStart=/bin/sh -c 'echo always | tee /sys/kernel/mm/transparent_hugepage/enabled > /dev/null && echo defer+madvise | tee /sys/kernel/mm/transparent_hugepage/defrag > /dev/null && echo 0 | tee /sys/kernel/mm/transparent_hugepage/khugepaged/max_ptes_none > /dev/null && echo 1 | tee /proc/sys/vm/overcommit_memory > /dev/null'

[Install]
WantedBy=basic.target
EOF
}


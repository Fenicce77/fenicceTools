    echo "${MSGCONFRSAUTHKEY}"
  else  
    MSGCONFRSAUTHKEY=`log_message "STANDARD" "[MONGODB][SETUP][REPLICASET][KEYFILE]" "INFO" "${MONGO_RS_KEYFILE_PATH} Not found! Creating Key File from the scratch"`
    echo "${MSGCONFRSAUTHKEY}"
    openssl rand -base64 756 > ${MONGO_RS_KEYFILE_PATH}
    if [[ $? -eq 0 ]]; then
    	MSGCONFRSAUTHKEYOK=`log_message "STANDARD" "[MONGODB][SETUP][REPLICASET][KEYFILE]" "OK" "MongoDB Key File created at : ${MONGO_RS_KEYFILE_PATH} !!"`
    	MSG=`log_message "STANDARD" "[MONGODB][SETUP][REPLICASET][KEYFILE]" "INFO" "Setting up permissions for ${MONGO_RS_KEYFILE_PATH} ..."`
    	echo "${MSGCONFRSAUTHKEY}"
    	echo "${MSG}"
    	chmod 400 ${MONGO_RS_KEYFILE_PATH}
      chown mongod:mongod ${MONGO_RS_KEYFILE_PATH}
      ### Interesting : copy to a bucket from primary and take it from secondary nodes
    	if [[ $? -eq 0 ]]; then
        MSGKEYFILEPERMOK=`log_message "STANDARD" "[MONGODB][SETUP][REPLICASET][KEYFILE]" "OK" "Permissions setted up for MongoDB Key File !!"`
        echo "${MSGKEYFILEPERMOK}"
        ls -lh ${MONGO_RS_KEYFILE_PATH}
      fi
    fi
  fi
else
  # -- Key File not generated in SECONDARY. Add entry in mongod configuration file.
  #    Report in output and remind to copy key file from Primary Node
  SECONDARYMSG1=`log_message "STANDARD" "[MONGODB][SETUP][REPLICASET][KEYFILE]" "INFO" "This node has been defined as SECONDARY"`
  SECONDARYMSG2=`log_message "STANDARD" "[MONGODB][SETUP][REPLICASET][KEYFILE]" "WARNING" "Please copy ${MONGO_RS_KEYFILE_PATH} from PRIMARY before starting MongoDB Server"`
  SECONDARYMSG3=`log_message "STANDARD" "[MONGODB][SETUP][REPLICASET][KEYFILE]" "INFO" "Key file path will be added to mongod configuration file"`
  echo "${SECONDARYMSG1}"
  echo "${SECONDARYMSG2}"
  echo "${SECONDARYMSG3}"
fi


